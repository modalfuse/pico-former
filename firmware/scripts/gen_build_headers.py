# PlatformIO pre-script.
# 1) include/ceqt_manifest.gen.h: list of weight arrays and SHA-256 digests of the weights and thresholds,
#    computed from include/ceqt_weights.h (float32 little-endian, header order; G_* golden arrays excluded).
#    The weights header is include/ceqt_weights.h unless the build flag CEQT_WEIGHTS=<file> names another
#    header in include/ (R1-3 second and third seeds).
# 2) include/ceqt_weights_active.gen.h: includes that header, or, when the build flag CEQT_CORRUPT=weight|thr
#    is set, a copy with one weight / threshold value changed (fault-injection builds F2/F3).
# 3) include/https_cert.gen.h: self-signed ECDSA P-256 certificate and key for the HTTPS endpoint
#    (generated once with openssl; local only).
# 4) include/api_token.gen.h: access token read from wifi.yaml key `api_token` (empty disables the check).

import hashlib
import re
import struct
import subprocess
from pathlib import Path

Import("env")  # noqa: F821

ROOT = Path(env["PROJECT_DIR"])  # noqa: F821
INC = ROOT / "include"
ARR = re.compile(r"static const float (\w+)\[(\d+)\]\s*=\s*\{(.*?)\};", re.S)


def flags():
    out = {}
    for f in env.ParseFlags(env["BUILD_FLAGS"]).get("CPPDEFINES", []):  # noqa: F821
        if isinstance(f, (list, tuple)):
            out[f[0]] = str(f[1]) if len(f) > 1 else "1"
        else:
            out[f] = "1"
    return out


def arrays(text):
    for m in ARR.finditer(text):
        vals = [float(v.strip().rstrip("f")) for v in m.group(3).replace("\n", " ").split(",") if v.strip()]
        if len(vals) != int(m.group(2)):
            raise SystemExit(f"{m.group(1)}: {len(vals)} values, expected {m.group(2)}")
        yield m.group(1), vals


def f32(vals):
    return b"".join(struct.pack("<f", v) for v in vals)


WEIGHTS_H = flags().get("CEQT_WEIGHTS", "ceqt_weights.h")
SRC_H = INC / WEIGHTS_H
text = SRC_H.read_text(encoding="utf-8")
items = list(arrays(text))
weights = [(n, v) for n, v in items if not n.startswith("G_") and n != "W_THR"]
thr = dict(items)["W_THR"]
hw = hashlib.sha256(b"".join(f32(v) for _, v in weights)).digest()
ht = hashlib.sha256(f32(thr)).digest()


def c_bytes(d):
    return ", ".join(f"0x{b:02x}" for b in d)


(INC / "ceqt_manifest.gen.h").write_text(
    "#pragma once\n// generated by scripts/gen_build_headers.py from ceqt_weights.h; do not edit\n"
    "#include <stdint.h>\n"
    "#define CEQT_MANIFEST_WEIGHTS " + " ".join(f"X({n})" for n, _ in weights) + "\n"
    f"static const uint8_t CEQT_SHA256_WEIGHTS[32] = {{{c_bytes(hw)}}};\n"
    f"static const uint8_t CEQT_SHA256_THRESHOLDS[32] = {{{c_bytes(ht)}}};\n"
    f'#define CEQT_SHA256_WEIGHTS_HEX "{hw.hex()}"\n'
    f'#define CEQT_SHA256_THRESHOLDS_HEX "{ht.hex()}"\n',
    encoding="utf-8",
)

corrupt = flags().get("CEQT_CORRUPT", "")
active = INC / "ceqt_weights_active.gen.h"
if corrupt in ("weight", "thr"):
    target = "W_EVT2" if corrupt == "weight" else "W_THR"
    m = re.search(rf"(static const float {target}\[\d+\]\s*=\s*\{{\s*)([-0-9.e+]+)f", text)
    old = float(m.group(2))
    new = struct.unpack("<f", struct.pack("<I", struct.unpack("<I", struct.pack("<f", old))[0] ^ 0x00000100))[0]
    bad = text[: m.start(2)] + repr(new) + text[m.end(2):]
    (INC / "ceqt_weights_corrupt.gen.h").write_text(bad, encoding="utf-8")
    active.write_text('#pragma once\n#include "ceqt_weights_corrupt.gen.h"\n', encoding="utf-8")
    print(f"CEQT_CORRUPT={corrupt}: {target}[0] {old!r} -> {new!r}")
else:
    active.write_text(f'#pragma once\n#include "{WEIGHTS_H}"\n', encoding="utf-8")

cert_h = INC / "https_cert.gen.h"
if not cert_h.exists():
    tmp = ROOT / ".pio" / "cert"
    tmp.mkdir(parents=True, exist_ok=True)
    subprocess.run(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", str(tmp / "key.pem")],
                   check=True)
    subprocess.run(["openssl", "req", "-new", "-x509", "-key", str(tmp / "key.pem"), "-out", str(tmp / "cert.pem"),
                    "-days", "825", "-subj", "/CN=pico-former.local"], check=True)

    def lit(p):
        return "".join(f'"{ln}\\n"\n' for ln in p.read_text().strip().splitlines())

    cert_h.write_text("#pragma once\n// generated locally; do not commit\n"
                      f"static const char HTTPS_CERT_PEM[] =\n{lit(tmp / 'cert.pem')};\n"
                      f"static const char HTTPS_KEY_PEM[] =\n{lit(tmp / 'key.pem')};\n", encoding="utf-8")

token = ""
yml = ROOT / "wifi.yaml"
if yml.is_file():
    for raw in yml.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line.lower().startswith("api_token:"):
            token = line.split(":", 1)[1].strip().strip("\"'")
(INC / "api_token.gen.h").write_text(
    "#pragma once\n// generated from wifi.yaml; do not edit\n" f'#define API_TOKEN "{token}"\n', encoding="utf-8")
print(f"manifest: {WEIGHTS_H}, {len(weights)} weight arrays, weights {hw.hex()[:12]}…, thresholds {ht.hex()[:12]}…, "
      f"token_set={bool(token)}")

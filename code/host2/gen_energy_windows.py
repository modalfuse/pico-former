#!/usr/bin/env python3
"""R2-9: generate the stored windows firmware/include/energy_windows.gen.h for the s3_energy test build.

Takes the first --n windows of the AZT1D held-out set whose reference status is 0 and packs them as audit-serial PFW2 frames (sequence number = 300000 + held-out index)
for periodic replay on the board in mode 12; after replay, run_energy_wifi.py reads back status and event bits via /api/history
and compares them window by window with the unloaded replay results/audit/azt1d_full. The header is generated from AZT1D data and is not committed to the repository.
Usage: python gen_energy_windows.py [--n 64]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import pf2  # noqa: E402
from run_wireless import CACHE, FW, REF  # noqa: E402

SEQ0 = 300000


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=64)
    args = ap.parse_args()
    ref = np.load(REF)
    ok = np.flatnonzero(ref["status"] == 0)[: args.n]
    idx = ref["idx"][ok]
    fr = pf2.frames(pf2.load_cache(CACHE)["test"])
    frames = [pf2.pack_window(SEQ0 + int(i), fr["n_marks"][i], fr["q"][i], fr["flags"][i], fr["t0_s"][i],
                              fr["t_last_s"][i], fr["y"][i], fr["feat"][i], fr["mask"][i]) for i in idx]
    size = len(frames[0])
    assert all(len(f) == size for f in frames)
    lines = ["#pragma once", "// generated by host2/gen_energy_windows.py from the AZT1D test split; do not edit or commit",
             f"// windows: AZT1D test indices {int(idx[0])}..{int(idx[-1])} with reference status 0; seq = {SEQ0} + index",
             "#include <stdint.h>", f"#define ENERGY_N_WINDOWS {len(frames)}", f"#define ENERGY_FRAME_LEN {size}",
             "static const uint8_t ENERGY_WINDOWS[ENERGY_N_WINDOWS][ENERGY_FRAME_LEN] = {"]
    for f in frames:
        lines.append("    {" + ",".join(str(b) for b in f) + "},")
    lines.append("};")
    out = FW / "include" / "energy_windows.gen.h"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    meta = {"n": len(frames), "frame_len": size, "seq0": SEQ0, "test_idx": [int(i) for i in idx],
            "ref_evt": [[int(v) for v in ref["evt"][k]] for k in ok], "ref_status": [int(v) for v in ref["status"][ok]]}
    (FW / "include" / "energy_windows.meta.json").write_text(json.dumps(meta), encoding="utf-8")
    print(out, len(frames), size)


if __name__ == "__main__":
    main()

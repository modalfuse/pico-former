#!/usr/bin/env python3
"""R2-15 design space: evaluation of 45 checkpoints on the AZT1D held-out set and two external cohorts, with paired comparison against the deployed configuration.

Datasets: AZT1D held-out set (split with seed 20260828, 5 participants), OhioT1DM (12), DiaTrend (17);
external windows are generated by build_external_cache.py. Input glucose is clipped to 40-400 mg/dL following
r2_4_r2_5_event_tables.py; targets are unchanged. Event thresholds are those calibrated for each checkpoint on the
AZT1D validation set (FPR budget 0.06); they are not recalibrated on the external cohorts.

Part 1: curve MAE over the 3 seeds of each configuration (ceqt.metrics.layer1_table, all trajectory points from 5 min
to the horizon) and FNR/FPR of 4 h hypo70 and hyper180; mean and standard deviation are written.
Part 2: paired comparison. The per-window error is the mean absolute error over trajectory points in 0-1 h and 0-4 h,
averaged over the 3 seeds and then subtracted from the deployed configuration (base); the FNR difference is the
difference of the 3-seed mean FNR. Confidence intervals use participant-level resampling with replacement
(N_BOOT draws); a window-level normal-approximation interval is also given for reference. Participant resampling
reflects only between-participant variation and treats the 3 seeds of each configuration as fixed; an interval with
joint participant and seed resampling (each draw resamples 3 seeds with replacement for the configuration and for
base independently) is also given to reflect training-seed variation.

Usage: python eval_grid_paired.py
Output: code/results/design_space/external/: <dataset>_perwin.npz, grid_external_summary.json,
        grid_external_table.md, paired_vs_base.csv, paired_vs_base.json
"""

from __future__ import annotations

import csv
import json
import pickle
import sys
import time
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
from train_grid import CACHE, OUT, Net, pack, predict  # noqa: E402

from ceqt.metrics import event_labels, layer1_table  # noqa: E402
from ceqt.ops.gate import residual_gate  # noqa: E402

EXT = Path(__file__).resolve().parents[1] / "results" / "external_cache"
RES = OUT / "external"
SEEDS = (20260828, 20260829, 20260830)
ORDER = ["d32_l1", "d32_l2", "d32_l3", "d48_l1", "base", "d48_l3", "d64_l1", "d64_l2", "d64_l3", "d96_l2",
         "L48", "L60", "L84", "h2", "h8"]
DATASETS = {"azt1d": CACHE, "ohio": EXT / "ohio_str15.pkl", "diatrend17": EXT / "diatrend17_str15.pkl"}
EVENTS = {"hypo70_1h": 0, "hypo70_4h": 3, "hyper180_1h": 8, "hyper180_4h": 11}  # value: column index in the 16-column event table
EV_COL = {ev: c for c, ev in enumerate(EVENTS)}  # per-window arrays store only these 4 columns
N_BOOT, BOOT_SEED = 2000, 20261009


def load_test(path):
    batch = pickle.loads(path.read_bytes())["test"]
    yh = np.asarray(batch.y_hist, np.float64)
    batch.y_hist = np.clip(yh, 40.0, 400.0).astype(np.asarray(batch.y_hist).dtype)
    return batch


def run_ckpt(name, seed, batch, dev):
    ck = torch.load(OUT / f"{name}_s{seed}.pt", map_location="cpu", weights_only=False)
    d, layers, heads, n_cgm, max_marks = ck["cfg"]
    net = Net(d, layers, heads, n_cgm, max_marks)
    net.load_state_dict(ck["state"])
    net.to(dev)
    yy, mm, kk, _, _, _, iner = pack(batch, ck["y_mean"], ck["y_std"], n_cgm, max_marks)
    dd, lg = predict(net, dev, yy, mm, kk)
    gate = residual_gate(batch.n_marks, batch.mark_a, batch.mark_e)
    yhat = iner + gate[:, None] * dd * ck["y_std"]
    pred = lg >= np.asarray(ck["thresholds"])[None, :]
    return yhat.astype(np.float64), pred


def per_dataset(ds, dev):
    f = RES / f"{ds}_perwin.npz"
    if f.exists():
        tj = np.load(f)["traj"]
        return {(name, seed): {1: tj[i, j, 0], 4: tj[i, j, 1]} for i, name in enumerate(ORDER) for j, seed in enumerate(SEEDS)}
    batch = load_test(DATASETS[ds])
    yf = np.asarray(batch.y_future, np.float64)
    hz = np.asarray(batch.horizons, float)
    lab = event_labels(batch.y_future, batch.horizons).astype(bool)
    n = len(yf)
    ae1 = np.zeros((len(ORDER), len(SEEDS), n), np.float32)
    ae4 = np.zeros_like(ae1)
    pred = np.zeros((len(ORDER), len(SEEDS), n, len(EVENTS)), bool)
    traj = {}
    for i, name in enumerate(ORDER):
        for j, seed in enumerate(SEEDS):
            yhat, p = run_ckpt(name, seed, batch, dev)
            ae = np.abs(yhat - yf)
            with np.errstate(invalid="ignore"):
                ae1[i, j] = np.nanmean(ae[:, hz <= 60], axis=1)
                ae4[i, j] = np.nanmean(ae[:, hz <= 240], axis=1)
            pred[i, j] = p[:, list(EVENTS.values())]
            traj[(name, seed)] = {int(r["ph"]) // 60: r["mae"] for r in layer1_table(batch.y_future, yhat, batch.horizons)}
        print(f"  {ds} {name} 4h MAE " + " ".join(f"{traj[(name, s)][4]:.2f}" for s in SEEDS), flush=True)
    tj = np.array([[[traj[(name, s)][1], traj[(name, s)][4]] for s in SEEDS] for name in ORDER])
    np.savez_compressed(f, ae1=ae1, ae4=ae4, pred=pred, lab=lab[:, list(EVENTS.values())],
                        subject=np.asarray(batch.subject_id).astype(str), traj=tj)
    return traj


def event_rates(lab, pred):
    pos, neg = lab.sum(0), (~lab).sum(0)
    fnr = ((~pred) & lab).sum(-2) / np.maximum(pos, 1)
    fpr = (pred & ~lab).sum(-2) / np.maximum(neg, 1)
    return fnr, fpr


def summary(ds, traj):
    z = np.load(RES / f"{ds}_perwin.npz")
    fnr, fpr = event_rates(z["lab"], z["pred"])
    rows = []
    for i, name in enumerate(ORDER):
        row = {"dataset": ds, "config": name}
        for h in (1, 4):
            v = np.array([traj[(name, s)][h] for s in SEEDS])
            row[f"traj_mae_{h}h_mean"], row[f"traj_mae_{h}h_sd"] = float(v.mean()), float(v.std(ddof=1))
        for ev, k in EV_COL.items():
            row[f"{ev}_fnr_mean"], row[f"{ev}_fnr_sd"] = float(fnr[i, :, k].mean()), float(fnr[i, :, k].std(ddof=1))
            row[f"{ev}_fpr_mean"], row[f"{ev}_fpr_sd"] = float(fpr[i, :, k].mean()), float(fpr[i, :, k].std(ddof=1))
        rows.append(row)
    return rows


def paired(ds):
    z = np.load(RES / f"{ds}_perwin.npz")
    subj = z["subject"]
    S, sidx = np.unique(subj, return_inverse=True)
    rng = np.random.default_rng(BOOT_SEED)
    W = rng.multinomial(len(S), np.full(len(S), 1 / len(S)), size=N_BOOT).astype(np.float64)
    nseed = len(SEEDS)

    def seed_draw():
        return rng.integers(0, nseed, size=(N_BOOT, nseed))

    def pick(x, d):  # x (N_BOOT, nseed) per-seed statistics; mean over the drawn seeds
        return np.take_along_axis(x, d, axis=1).mean(1)
    ib = list(ORDER).index("base")
    lab, pred = z["lab"], z["pred"]
    out = []
    for i, name in enumerate(ORDER):
        if i == ib:
            continue
        row = {"dataset": ds, "config": name, "n_windows": int(len(subj)), "n_subjects": int(len(S))}
        for key in ("ae1", "ae4"):
            a = z[key].astype(np.float64)
            dw = np.nanmean(a[i], 0) - np.nanmean(a[ib], 0)
            ok = np.isfinite(dw)
            dw, si = dw[ok], sidx[ok]
            ssum = np.bincount(si, dw, len(S))
            scnt = np.bincount(si, None, len(S))
            boot = (W @ ssum) / (W @ scnt)
            m = float(dw.mean())
            se = float(dw.std(ddof=1) / np.sqrt(len(dw)))
            per_s = ssum / np.maximum(scnt, 1)
            h = key[2:]
            row[f"dmae_{h}h"] = m
            row[f"dmae_{h}h_ci_subj"] = [float(np.percentile(boot, 2.5)), float(np.percentile(boot, 97.5))]
            row[f"dmae_{h}h_ci_win"] = [m - 1.96 * se, m + 1.96 * se]
            row[f"dmae_{h}h_subj_better"] = int((per_s < 0).sum())
            ok_all = np.isfinite(a[i]).all(0) & np.isfinite(a[ib]).all(0)
            cnt = np.bincount(sidx[ok_all], None, len(S))
            si_c = np.stack([np.bincount(sidx[ok_all], a[i, j][ok_all], len(S)) for j in range(nseed)])
            si_b = np.stack([np.bincount(sidx[ok_all], a[ib, j][ok_all], len(S)) for j in range(nseed)])
            den = (W @ cnt)[:, None]
            bs = pick((W @ si_c.T) / den, seed_draw()) - pick((W @ si_b.T) / den, seed_draw())
            row[f"dmae_{h}h_ci_subj_seed"] = [float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]
        for ev, k in EV_COL.items():
            if not ev.endswith("4h"):
                continue
            y = lab[:, k]
            # false negatives and positives per participant and seed, for participant resampling
            pos = np.bincount(sidx, y.astype(float), len(S))
            fn_c = np.stack([np.bincount(sidx, ((~pred[i, j, :, k]) & y).astype(float), len(S)) for j in range(3)])
            fn_b = np.stack([np.bincount(sidx, ((~pred[ib, j, :, k]) & y).astype(float), len(S)) for j in range(3)])
            d_pt = float((fn_c.sum(1) - fn_b.sum(1)).mean() / max(pos.sum(), 1))
            P = W @ pos
            with np.errstate(invalid="ignore", divide="ignore"):
                boot = ((W @ fn_c.T).mean(1) - (W @ fn_b.T).mean(1)) / P
            boot = boot[np.isfinite(boot)]
            row[f"d{ev}_fnr"] = d_pt
            row[f"d{ev}_fnr_ci_subj"] = [float(np.percentile(boot, 2.5)), float(np.percentile(boot, 97.5))]
            with np.errstate(invalid="ignore", divide="ignore"):
                bs = pick((W @ fn_c.T) / P[:, None], seed_draw()) - pick((W @ fn_b.T) / P[:, None], seed_draw())
            bs = bs[np.isfinite(bs)]
            row[f"d{ev}_fnr_ci_subj_seed"] = [float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]
            row[f"{ev}_n_pos"] = int(pos.sum())
        out.append(row)
    return out


def fmt_ci(v, ci, nd=2):
    return f"{v:+.{nd}f} [{ci[0]:+.{nd}f}, {ci[1]:+.{nd}f}]"


def main():
    RES.mkdir(parents=True, exist_ok=True)
    dev = torch.device("mps" if torch.backends.mps.is_available() else "cpu")
    t0 = time.time()
    summ, pair = [], []
    for ds in DATASETS:
        traj = per_dataset(ds, dev)
        summ += summary(ds, traj)
        pair += paired(ds)
        print(f"{ds} done {time.time() - t0:.0f} s", flush=True)
    (RES / "grid_external_summary.json").write_text(json.dumps(summ, indent=1), encoding="utf-8")
    (RES / "paired_vs_base.json").write_text(json.dumps(pair, indent=1), encoding="utf-8")
    with (RES / "paired_vs_base.csv").open("w", newline="", encoding="utf-8") as f:
        flat = [{k: (json.dumps(v) if isinstance(v, list) else v) for k, v in r.items()} for r in pair]
        w = csv.DictWriter(f, fieldnames=list(flat[0]))
        w.writeheader()
        w.writerows(flat)

    lines = ["# R2-15 design space: curve MAE and 4 h event metrics on three datasets (3 seeds, mean ± SD)", ""]
    for ds in DATASETS:
        lines += [f"## {ds}", "", "| Configuration | MAE 1 h | MAE 4 h | hypo70 4 h FNR | hypo70 4 h FPR | hyper180 4 h FNR | hyper180 4 h FPR |",
                  "|" + " --- |" * 7]
        for r in (r for r in summ if r["dataset"] == ds):
            lines.append(f"| {r['config']} | {r['traj_mae_1h_mean']:.2f} ± {r['traj_mae_1h_sd']:.2f} | "
                         f"{r['traj_mae_4h_mean']:.2f} ± {r['traj_mae_4h_sd']:.2f} | "
                         f"{r['hypo70_4h_fnr_mean']:.3f} ± {r['hypo70_4h_fnr_sd']:.3f} | "
                         f"{r['hypo70_4h_fpr_mean']:.3f} ± {r['hypo70_4h_fpr_sd']:.3f} | "
                         f"{r['hyper180_4h_fnr_mean']:.3f} ± {r['hyper180_4h_fnr_sd']:.3f} | "
                         f"{r['hyper180_4h_fpr_mean']:.3f} ± {r['hyper180_4h_fpr_sd']:.3f} |")
        lines += ["", f"### {ds}: paired difference vs base (configuration minus base; 95% intervals, first from participant resampling, second from joint participant and seed resampling)", "",
                  "| Configuration | ΔMAE 1 h | ΔMAE 4 h | Participants with lower 4 h error | Δhypo70 4 h FNR | Δhyper180 4 h FNR |",
                  "|" + " --- |" * 6]

        def two(r, k, nd=2):
            a, b = r[f"{k}_ci_subj"], r[f"{k}_ci_subj_seed"]
            return f"{r[k]:+.{nd}f} [{a[0]:+.{nd}f}, {a[1]:+.{nd}f}] [{b[0]:+.{nd}f}, {b[1]:+.{nd}f}]"
        for r in (r for r in pair if r["dataset"] == ds):
            lines.append(f"| {r['config']} | {two(r, 'dmae_1h')} | {two(r, 'dmae_4h')} | "
                         f"{r['dmae_4h_subj_better']}/{r['n_subjects']} | {two(r, 'dhypo70_4h_fnr', 3)} | "
                         f"{two(r, 'dhyper180_4h_fnr', 3)} |")
        lines.append("")
    (RES / "grid_external_table.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"all done {time.time() - t0:.0f} s", flush=True)


if __name__ == "__main__":
    main()

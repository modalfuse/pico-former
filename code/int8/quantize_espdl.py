#!/usr/bin/env python3
"""R2-14 step 2 (glucobench environment, ESP-PPQ 1.3.9): post-training quantization of the full model (encoder + cross-attention + two heads) and execution on the host.

The quantized graph takes the 96×48 token matrix (generated by prep_int8_data.py) and outputs the clipped standardized delta (48) and 16 logits;
the inertial baseline, residual gate and threshold comparison are done in FP32 by C code at deployment, and likewise in the evaluation script.
The ESP-DL operator set has no Gelu or Erf, so GELU in the graph uses the tanh approximation; a floating-point version of the same graph (fp32tanh) is also exported
to separate the differences caused by the GELU approximation from those caused by quantization.
With --gelu exact, GELU is expressed as F.gelu (erf form) and fused by ESP-PPQ into a single lookup-table operator; the default is the tanh approximation.
Usage: python quantize_espdl.py --bits 8|16 [--gelu tanh|exact] [--limit N]
      Mixed precision: --int16-ops /MatMul_34,... dispatches the listed operators as INT16 and the rest per --bits;
      --quant-type w8a16 uses 8-bit weights and 16-bit activations; both require --tag to name the output.
Output in code/results/int8/:
  rebuild_check.json (difference between the rewritten floating-point exact-GELU graph and the FP32 reference);
  fp32tanh_{val,test}.npz；q<bits>_{val,test}.npz（logits、delta_norm）；
  espdl/ceqt_int<bits>.espdl and its .info/.json/.onnx.
"""

from __future__ import annotations

import argparse
import json
import math
import time
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.utils.data import DataLoader, TensorDataset

HERE = Path(__file__).resolve().parent
RES = HERE.parent / "results" / "int8"
D, H, DK, N_TOK = 48, 4, 12, 96
GELU_K = math.sqrt(2.0 / math.pi)


def gelu_tanh(x):
    return 0.5 * x * (1.0 + torch.tanh(GELU_K * (x + 0.044715 * x * x * x)))


class TokenModel(nn.Module):
    """Encoder (2 post-norm layers, ReLU FFN) + shared cross-attention + delta/event heads, written with ONNX-friendly ops."""

    def __init__(self, sd: dict, exact_gelu: bool = False):
        super().__init__()
        self.exact = exact_gelu
        for k, v in sd.items():
            if k.startswith(("enc.", "cross.", "delta_head.", "evt_head.", "curve_q", "event_q")):
                self.register_buffer(k.replace(".", "_"), v.detach().float().clone())

    def b(self, name):
        return getattr(self, name.replace(".", "_"))

    def gelu(self, x):
        return F.gelu(x) if self.exact else gelu_tanh(x)

    def mha(self, q, kv, p):
        w, bias = self.b(f"{p}.in_proj_weight"), self.b(f"{p}.in_proj_bias")
        Q = F.linear(q, w[:D], bias[:D])
        K = F.linear(kv, w[D:2 * D], bias[D:2 * D])
        V = F.linear(kv, w[2 * D:], bias[2 * D:])
        parts = []
        for hd in range(H):
            sl = slice(hd * DK, (hd + 1) * DK)
            s = torch.matmul(Q[..., sl], K[..., sl].transpose(-1, -2)) * (1.0 / math.sqrt(DK))
            parts.append(torch.matmul(torch.softmax(s, dim=-1), V[..., sl]))
        return F.linear(torch.cat(parts, dim=-1), self.b(f"{p}.out_proj.weight"), self.b(f"{p}.out_proj.bias"))

    def forward(self, tok):
        x = tok
        for i in range(2):
            p = f"enc.layers.{i}"
            x = F.layer_norm(x + self.mha(x, x, f"{p}.self_attn"), (D,), self.b(f"{p}.norm1.weight"), self.b(f"{p}.norm1.bias"), 1e-5)
            ff = F.linear(F.relu(F.linear(x, self.b(f"{p}.linear1.weight"), self.b(f"{p}.linear1.bias"))),
                          self.b(f"{p}.linear2.weight"), self.b(f"{p}.linear2.bias"))
            x = F.layer_norm(x + ff, (D,), self.b(f"{p}.norm2.weight"), self.b(f"{p}.norm2.bias"), 1e-5)
        bsz = tok.shape[0]
        c = self.mha(self.b("curve_q").unsqueeze(0).expand(bsz, -1, -1), x, "cross")
        e = self.mha(self.b("event_q").unsqueeze(0).expand(bsz, -1, -1), x, "cross")
        dh = F.linear(self.gelu(F.linear(c, self.b("delta_head.0.weight"), self.b("delta_head.0.bias"))),
                      self.b("delta_head.2.weight"), self.b("delta_head.2.bias")).squeeze(-1)
        delta = 40.0 * torch.tanh(dh / 40.0)
        logits = F.linear(self.gelu(F.linear(e, self.b("evt_head.0.weight"), self.b("evt_head.0.bias"))),
                          self.b("evt_head.2.weight"), self.b("evt_head.2.bias")).squeeze(-1)
        return delta, logits


@torch.no_grad()
def run_float(model, tok, dtype=torch.float32):
    m = model.to(dtype)
    d_l, l_l = [], []
    for s in range(0, len(tok), 1024):
        d, l = m(torch.from_numpy(np.asarray(tok[s:s + 1024])).to(dtype))
        d_l.append(d.double().numpy())
        l_l.append(l.double().numpy())
    model.float()
    return np.concatenate(d_l), np.concatenate(l_l)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bits", type=int, default=8)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--gelu", choices=("tanh", "exact"), default="tanh")
    ap.add_argument("--int16-ops", default="")
    ap.add_argument("--quant-type", default=None)
    ap.add_argument("--tag", default=None)
    args = ap.parse_args()
    blob = torch.load(RES / "state_s20260828.pt", map_location="cpu", weights_only=False)
    sd, y_std = blob["state"], float(blob["y_std"])
    tok = {s: np.load(RES / f"tok_{s}.npy", mmap_mode="r") for s in ("calib", "val", "test")}
    side = {s: np.load(RES / f"side_{s}.npz") for s in ("val", "test")}

    # 1) the rewritten graph with exact GELU must reproduce the FP32 reference
    chk = {}
    exact = TokenModel(sd, exact_gelu=True).eval()
    d, l = run_float(exact, tok["test"], torch.float64)
    yh = side["test"]["iner"] + side["test"]["g"][:, None] * d * y_std
    chk["exact_f64_logit_maxabs"] = float(np.abs(l - side["test"]["logits_fp32"]).max())
    chk["exact_f64_yhat_maxabs"] = float(np.abs(yh - side["test"]["yhat_fp32"]).max())
    print("rebuild", chk, flush=True)
    (RES / "rebuild_check.json").write_text(json.dumps(chk, indent=1))
    if chk["exact_f64_logit_maxabs"] > 1e-4:
        raise SystemExit("rewritten graph does not match the FP32 reference")

    exact_g = args.gelu == "exact"
    sfx = "e" if exact_g else ""
    model = TokenModel(sd, exact_gelu=exact_g).eval()
    if not exact_g and not (RES / "fp32tanh_test.npz").exists():
        for s in ("val", "test"):
            d, l = run_float(model, tok[s])
            np.savez_compressed(RES / f"fp32tanh_{s}.npz", logits=l, delta_norm=d)
        print("fp32tanh done", flush=True)

    from esp_ppq.api import espdl_quantize_torch
    from esp_ppq.core import TargetPlatform
    from esp_ppq.executor.torch import TorchExecutor

    calib = torch.from_numpy(np.ascontiguousarray(tok["calib"]))
    loader = DataLoader(TensorDataset(calib), batch_size=1, shuffle=False)
    out_dir = RES / "espdl"
    out_dir.mkdir(exist_ok=True)
    tag = args.tag or f"q{args.bits}{sfx}"
    espdl_name = f"ceqt_{tag}.espdl" if args.tag else f"ceqt_int{args.bits}{sfx}.espdl"
    override = {op: TargetPlatform.ESPDL_S3_INT16 for op in args.int16_ops.split(",") if op} or None
    t0 = time.time()
    graph = espdl_quantize_torch(
        model=model, espdl_export_file=str(out_dir / espdl_name), calib_dataloader=loader,
        calib_steps=len(calib), input_shape=[1, N_TOK, D], target="esp32s3", num_of_bits=args.bits,
        collate_fn=lambda b: b[0].to("cpu"), device="cpu", error_report=True, skip_export=False,
        export_test_values=True, verbose=1, opset_version=17,
        dispatching_override=override, quant_type=args.quant_type,
    )
    print(f"quantized in {time.time() - t0:.0f} s", flush=True)
    ex = TorchExecutor(graph=graph, device="cpu")
    for s in ("val", "test"):
        n = len(tok[s]) if not args.limit else min(args.limit, len(tok[s]))
        lg = np.zeros((n, 16))
        dn = np.zeros((n, 48))
        t1 = time.time()
        with torch.no_grad():
            for i in range(n):
                o = ex(torch.from_numpy(np.array(tok[s][i:i + 1])))
                dn[i] = o[0].detach().double().numpy().reshape(48)
                lg[i] = o[1].detach().double().numpy().reshape(16)
                if (i + 1) % 2000 == 0:
                    print(f"  {s} {i + 1}/{n} {(time.time() - t1) / (i + 1) * 1000:.1f} ms/win", flush=True)
        np.savez_compressed(RES / f"{tag}_{s}.npz", logits=lg, delta_norm=dn)
        print(s, "logit maxabs vs fp32", float(np.abs(lg - side[s]["logits_fp32"][:n]).max()), flush=True)


if __name__ == "__main__":
    main()
